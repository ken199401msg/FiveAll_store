-- 五眾店務管理：登入、角色、店別授權、登入紀錄、操作紀錄
-- 狀態：草稿，尚未套用到資料庫

-- 1. 使用者資料（對應 Supabase Auth 帳號）
create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null,
  role text not null check (role in ('admin','manager','accountant')),
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

-- 2. 店別授權（店長可有一筆或多筆；店別名稱同 daily_reports.store）
create table public.user_stores (
  user_id uuid not null references public.profiles(id) on delete cascade,
  store_name text not null,
  primary key (user_id, store_name)
);

-- 3. 登入登出紀錄
create table public.auth_logs (
  id bigint generated by default as identity primary key,
  user_id uuid,
  email text,
  event text not null check (event in ('login','logout','login_failed')),
  ip text,
  user_agent text,
  created_at timestamptz not null default now()
);

-- 4. 操作紀錄（web=網頁、line=LINE機器人或後台、system）
create table public.audit_logs (
  id bigint generated by default as identity primary key,
  user_id uuid,
  email text,
  source text not null default 'web' check (source in ('web','line','system')),
  action text not null,
  table_name text,
  record_id text,
  store text,
  old_data jsonb,
  new_data jsonb,
  detail jsonb,
  created_at timestamptz not null default now()
);
create index on public.auth_logs (user_id, created_at desc);
create index on public.audit_logs (user_id, created_at desc);
create index on public.audit_logs (table_name, created_at desc);

alter table public.profiles enable row level security;
alter table public.user_stores enable row level security;
alter table public.auth_logs enable row level security;
alter table public.audit_logs enable row level security;

-- 5. 權限輔助函式
create or replace function public.app_role() returns text
language sql stable security definer set search_path = public as $$
  select role from public.profiles where id = auth.uid() and is_active
$$;

create or replace function public.app_stores() returns text[]
language sql stable security definer set search_path = public as $$
  select coalesce(array_agg(us.store_name), '{}')
  from public.user_stores us
  join public.profiles p on p.id = us.user_id
  where us.user_id = auth.uid() and p.is_active
$$;

create or replace function public.can_see_store(s text) returns boolean
language sql stable security definer set search_path = public as $$
  select case public.app_role()
    when 'admin' then true
    when 'accountant' then true
    when 'manager' then s = any(public.app_stores())
    else false end
$$;

-- 6. 寫入紀錄的函式（前端只能透過這兩個函式寫紀錄）
create or replace function public.log_auth_event(p_event text) returns void
language plpgsql security definer set search_path = public as $$
declare h json := nullif(current_setting('request.headers', true), '')::json;
begin
  insert into public.auth_logs(user_id, email, event, ip, user_agent)
  values (auth.uid(), auth.jwt()->>'email', p_event,
          h->>'x-forwarded-for', h->>'user-agent');
end $$;

create or replace function public.log_action(
  p_action text, p_table text default null, p_record text default null,
  p_store text default null, p_detail jsonb default null) returns void
language plpgsql security definer set search_path = public as $$
begin
  if public.app_role() is null then return; end if;
  insert into public.audit_logs(user_id, email, source, action, table_name, record_id, store, detail)
  values (auth.uid(), auth.jwt()->>'email', 'web', p_action, p_table, p_record, p_store, p_detail);
end $$;

-- 7. 資料表異動自動記錄（LINE 修改日報表也會留下紀錄）
create or replace function public.audit_row_change() returns trigger
language plpgsql security definer set search_path = public as $$
declare r jsonb := case when tg_op = 'DELETE' then to_jsonb(old) else to_jsonb(new) end;
begin
  insert into public.audit_logs(user_id, email, source, action, table_name, record_id, store, old_data, new_data)
  values (auth.uid(), auth.jwt()->>'email',
          case when auth.uid() is null then 'line' else 'web' end,
          tg_op, tg_table_name, r->>'id', r->>'store',
          case when tg_op = 'INSERT' then null else to_jsonb(old) end,
          case when tg_op = 'DELETE' then null else to_jsonb(new) end);
  return null;
end $$;

create trigger audit_daily_reports after insert or update or delete on public.daily_reports
  for each row execute function public.audit_row_change();
create trigger audit_daily_report_items after insert or update or delete on public.daily_report_items
  for each row execute function public.audit_row_change();
create trigger audit_weekly_settlements after insert or update or delete on public.weekly_settlements
  for each row execute function public.audit_row_change();
create trigger audit_petty_cash_receipts after insert or update or delete on public.petty_cash_receipts
  for each row execute function public.audit_row_change();
create trigger audit_profiles after insert or update or delete on public.profiles
  for each row execute function public.audit_row_change();
create trigger audit_user_stores after insert or update or delete on public.user_stores
  for each row execute function public.audit_row_change();

-- 8. RLS：網頁端一律唯讀（資料修改只走 LINE）
create policy web_read_profiles on public.profiles for select to authenticated
  using (id = auth.uid() or public.app_role() = 'admin');
create policy web_read_user_stores on public.user_stores for select to authenticated
  using (user_id = auth.uid() or public.app_role() = 'admin');
create policy admin_read_auth_logs on public.auth_logs for select to authenticated
  using (public.app_role() = 'admin');
create policy admin_read_audit_logs on public.audit_logs for select to authenticated
  using (public.app_role() = 'admin');

create policy web_read_daily_reports on public.daily_reports for select to authenticated
  using (public.can_see_store(store));
create policy web_read_daily_report_items on public.daily_report_items for select to authenticated
  using (exists (select 1 from public.daily_reports d
                 where d.id = report_id and public.can_see_store(d.store)));
create policy web_read_weekly_settlements on public.weekly_settlements for select to authenticated
  using (public.can_see_store(store));
create policy web_read_petty_cash_receipts on public.petty_cash_receipts for select to authenticated
  using (public.can_see_store(store));
create policy web_read_petty_cash_photos on public.petty_cash_photos for select to authenticated
  using (exists (select 1 from public.petty_cash_receipts r
                 where r.batch_id = petty_cash_photos.batch_id and public.can_see_store(r.store)));
create policy web_read_therapists on public.therapists for select to authenticated
  using (public.app_role() is not null);
create policy web_read_stores on public.stores for select to authenticated
  using (public.app_role() is not null);

-- 9. 函式權限：匿名使用者不可呼叫
revoke execute on function public.log_auth_event(text) from public, anon;
revoke execute on function public.log_action(text,text,text,text,jsonb) from public, anon;
grant execute on function public.log_auth_event(text) to authenticated;
grant execute on function public.log_action(text,text,text,text,jsonb) to authenticated;

-- 10. 整個專案唯讀：收回網頁端（anon / authenticated）所有寫入權限
--     LINE 機器人使用 service_role，不受影響
do $$
declare r record;
begin
  for r in select c.relname from pg_class c join pg_namespace n on n.oid = c.relnamespace
           where n.nspname = 'public' and c.relkind in ('r','v','m','p') loop
    execute format('revoke insert, update, delete, truncate on public.%I from anon, authenticated', r.relname);
  end loop;
end $$;
revoke all on public.profiles, public.user_stores, public.auth_logs, public.audit_logs from anon;

revoke execute on function public.app_role(), public.app_stores(), public.can_see_store(text) from public, anon;
grant execute on function public.app_role(), public.app_stores(), public.can_see_store(text) to authenticated;
