-- 日帳記事（網頁可寫入的例外之一）；寫入只能透過下列函式

create table public.daily_notes (
  id bigint generated by default as identity primary key,
  store text not null,
  note_date date not null,
  content text not null check (char_length(content) between 1 and 1000),
  created_by uuid not null,
  created_by_name text not null,
  created_at timestamptz not null default now()
);
create index on public.daily_notes (store, note_date);
alter table public.daily_notes enable row level security;

create policy web_read_daily_notes on public.daily_notes for select to authenticated
  using (public.can_see_store(store));

create trigger audit_daily_notes after insert or update or delete on public.daily_notes
  for each row execute function public.audit_row_change();

-- 新增記事：超級管理員、帳務人員（全店）、店長（限授權店）
create or replace function public.note_add(p_store text, p_date date, p_content text) returns bigint
language plpgsql security definer set search_path = public as $$
declare v_role text := public.app_role(); v_id bigint; v_name text;
begin
  if v_role is null or v_role = 'pending' then raise exception 'forbidden'; end if;
  if v_role = 'manager' and not (p_store = any(public.app_stores())) then raise exception 'forbidden'; end if;
  select display_name into v_name from public.profiles where id = auth.uid();
  insert into public.daily_notes(store, note_date, content, created_by, created_by_name)
  values (p_store, p_date, btrim(p_content), auth.uid(), v_name) returning id into v_id;
  return v_id;
end $$;

-- 刪除記事：本人或超級管理員
create or replace function public.note_delete(p_id bigint) returns void
language plpgsql security definer set search_path = public as $$
begin
  delete from public.daily_notes
  where id = p_id and (created_by = auth.uid() or public.app_role() = 'admin');
  if not found then raise exception 'forbidden'; end if;
end $$;

revoke all on public.daily_notes from anon;
revoke insert, update, delete, truncate on public.daily_notes from authenticated;
revoke execute on function public.note_add(text,date,text), public.note_delete(bigint) from public, anon;
grant execute on function public.note_add(text,date,text), public.note_delete(bigint) to authenticated;
